#!/usr/bin/env bash
# netsurf_fuentes.sh - descarga y prepara las fuentes de NetSurf (D184).
#
# NetSurf (https://www.netsurf-browser.org/) es GPL-2.0 y sus bibliotecas son
# MIT. Las fuentes (unos 90 MB descomprimidas) NO van en git: este guion baja
# el tarball "netsurf-all" de una versión publicada, comprueba su SHA-256, lo
# descomprime en userland/terceros/netsurf/fuentes/ (ignorada por git) y
# genera lo que el sistema de construcción de NetSurf genera con herramientas
# del anfitrión:
#
#   - libparserutils: src/charset/aliases.inc (perl, guion del upstream)
#   - libhubbub:      src/tokeniser/entities.inc (perl, guion del upstream)
#   - libhubbub:      src/treebuilder/autogenerated-element-type.c (el upstream
#                     usa gperf, que no está en el anfitrión; lo genera
#                     tools/netsurf_gerar.py con la misma interfaz)
#   - libcss:         src/parse/properties/autogenerated_*.c (el generador en C
#                     del upstream, compilado con el gcc del anfitrión)
#   - netsurf:        la fuente interna del frontend framebuffer (convert_font
#                     del upstream), las imágenes de la barra (el upstream usa
#                     convert_image con libpng; aquí tools/netsurf_gerar.py),
#                     el fichero Messages (el upstream usa split-messages, que
#                     pide zlib o HTML::Entities; aquí tools/netsurf_gerar.py,
#                     sin comprimir) y testament.h.
#
#   tools/netsurf_fuentes.sh [--tarball FICHERO] [--forzar]
#
#   --tarball FICHERO  usar un tarball ya descargado (se comprueba igual el SHA-256)
#   --forzar           borrar lo preparado y volver a empezar
#
# Al final deja userland/terceros/netsurf/fuentes/.preparado: el Makefile solo
# compila /bin/netsurf si existe (sin las fuentes, el sistema se construye igual,
# sin el navegador).
set -euo pipefail

VERSAO=3.11
URL="https://download.netsurf-browser.org/netsurf/releases/source-full/netsurf-all-${VERSAO}.tar.gz"
SHA256=4dea880ff3c2f698bfd62c982b259340f9abcd7f67e6c8eb2b32c61f71644b7b

RAIZ="$(cd "$(dirname "$0")/.." && pwd)"
DEST="$RAIZ/userland/terceros/netsurf/fuentes"
SRC="$DEST/netsurf-all-${VERSAO}"
GER="$DEST/gerado"
TARBALL=""
FORZAR=0

while [ $# -gt 0 ]; do
    case "$1" in
        --tarball) TARBALL="$2"; shift 2 ;;
        --forzar)  FORZAR=1; shift ;;
        -h|--help|--ayuda) sed -n '2,32p' "$0"; exit 0 ;;
        *) echo "netsurf_fuentes.sh: opción desconocida: $1" >&2; exit 2 ;;
    esac
done

if [ -f "$DEST/.preparado" ] && [ "$FORZAR" = 0 ]; then
    echo "netsurf_fuentes.sh: ya preparado en $DEST (--forzar para rehacer)"
    exit 0
fi

# El gcc del anfitrión (los generadores en C del upstream) viene del entorno local.
if ! command -v gcc >/dev/null 2>&1 && [ -f "$HOME/.local/saguitools/env.sh" ]; then
    # shellcheck disable=SC1091
    . "$HOME/.local/saguitools/env.sh"
fi
for h in gcc perl python3 sha256sum tar; do
    command -v "$h" >/dev/null 2>&1 || { echo "netsurf_fuentes.sh: falta $h" >&2; exit 1; }
done

mkdir -p "$DEST"
# Lo extraído se prepara en una carpeta temporal y solo al final se renombra:
# un corte a medias no deja un árbol que parezca bueno.
TMP="$(mktemp -d "$DEST/tmp.XXXXXX")"
trap 'rm -rf "$TMP"' EXIT

if [ -z "$TARBALL" ]; then
    TARBALL="$DEST/netsurf-all-${VERSAO}.tar.gz"
    if [ ! -f "$TARBALL" ]; then
        echo "netsurf_fuentes.sh: descargando $URL"
        curl -fsSL -o "$TMP/descarga.tar.gz" "$URL"
        mv "$TMP/descarga.tar.gz" "$TARBALL"
    fi
fi
echo "$SHA256  $TARBALL" | sha256sum -c --quiet - || {
    echo "netsurf_fuentes.sh: el SHA-256 de $TARBALL no es el esperado" >&2
    exit 1
}

tar xzf "$TARBALL" -C "$TMP"
S="$TMP/netsurf-all-${VERSAO}"
G="$TMP/gerado"
mkdir -p "$G/ferramentas"

# libparserutils y libhubbub: los guiones perl escriben en rutas relativas.
( cd "$S/libparserutils" && perl build/make-aliases.pl )
( cd "$S/libhubbub" && perl build/make-entities.pl )

# libhubbub: la tabla de elementos (gperf en el upstream).
python3 -I "$RAIZ/tools/netsurf_gerar.py" elementos \
    "$S/libhubbub/src/treebuilder/element-type.gperf" \
    "$S/libhubbub/src/treebuilder/autogenerated-element-type.c"

# libcss: un analizador por cada propiedad de properties.gen.
P="$S/libcss/src/parse/properties"
gcc -O1 -o "$G/ferramentas/gen_parser" "$P/css_property_parser_gen.c"
grep -E '^[^#][^:]+:' "$P/properties.gen" | while IFS= read -r linha; do
    nome="${linha%%:*}"
    ( cd "$S/libcss" && "$G/ferramentas/gen_parser" -o "src/parse/properties/autogenerated_${nome}.c" "$linha" )
done

# netsurf (frontend framebuffer): fuente interna, imágenes, mensajes, testament.
N="$S/netsurf"
gcc -O1 -o "$G/ferramentas/convert_font" "$N/tools/convert_font.c"
"$G/ferramentas/convert_font" -H "$G/font-ns-sans.h" \
    "$N/frontends/framebuffer/res/fonts/glyph_data" "$G/font-ns-sans.c" >/dev/null
python3 -I "$RAIZ/tools/netsurf_gerar.py" imagens "$N/frontends/framebuffer/Makefile" \
    "$N/frontends/framebuffer/res" "$G"
mkdir -p "$G/res/en"
python3 -I "$RAIZ/tools/netsurf_gerar.py" mensagens "$N/resources/FatMessages" en fb "$G/res/en/Messages"
python3 -I "$RAIZ/tools/netsurf_gerar.py" testament "$G/testament.h" "$VERSAO"

# Las cabeceras de la "binding" de libdom con libhubbub, donde las deja el
# "make install" del upstream (NetSurf las pide como dom/bindings/hubbub/...).
mkdir -p "$G/include/dom/bindings/hubbub"
cp "$S/libdom/bindings/hubbub/parser.h" "$S/libdom/bindings/hubbub/errors.h" "$G/include/dom/bindings/hubbub/"

rm -rf "$SRC" "$GER"
mv "$S" "$SRC"
mv "$G" "$GER"
echo "$VERSAO $SHA256" > "$DEST/.preparado"
echo "netsurf_fuentes.sh: preparado en $DEST"
