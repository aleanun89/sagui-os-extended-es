-- ejemplo_valkey.lua - cliente de Valkey en Lua (D477): lua ejemplo_valkey.lua [host [puerto]]
local valkey = require("valkey")
local r = assert(valkey.conectar(arg[1] or "127.0.0.1", tonumber(arg[2]) or 6379))
print("PING", r:ping())
r:del("lua:n", "lua:l", "lua:h")
r:set("lua:clave", "valor desde Lua")
print("GET", r:get("lua:clave"))
r:incr("lua:n"); r:incrby("lua:n", 41)
print("INCR", r:get("lua:n"))
r:rpush("lua:l", "a", "b", "c")
print("LRANGE", table.concat(r:lrange("lua:l", 0, -1), ","))
r:hset("lua:h", "nombre", "SaguiOS")
print("HGETALL", r:hgetall("lua:h").nombre)
r:set("lua:t", "x"); r:expire("lua:t", 100)
print("TTL", r:ttl("lua:t") > 0)
r:cerrar()
